        -l strimzi.io/component-type=kafka -n azul-infra --timeout=300s 2>/dev/null \
        && log "  Kafka: READY" || log "  WARNING: Kafka not ready within 300s"

    log "  MinIO (label: app=s3-store-minio)..."
    kubectl wait --for=condition=ready pod \
        -l app=s3-store-minio -n azul-infra --timeout=180s 2>/dev/null \
        && log "  MinIO: READY" || log "  WARNING: MinIO not ready within 180s"

    log "  Postgres (label: app=postgres)..."
    kubectl wait --for=condition=ready pod \
        -l app=postgres -n azul-infra --timeout=180s 2>/dev/null \
        && log "  Postgres: READY" || log "  WARNING: Postgres not ready within 180s"

