# CHECK — just show current state
# ═══════════════════════════════════════════════════════════════════════════════
cmd_check() {
    log "=== Current Infrastructure State ==="
    log ""
    log "Namespaces:"
    for ns in kafka opensearch-operator azul-infra; do
        if kubectl get namespace "$ns" >/dev/null 2>&1; then
            local count
            count=$(kubectl get pods -n "$ns" --no-headers 2>/dev/null | wc -l)
            log "  $ns: EXISTS ($count pods)"
        else
            log "  $ns: NOT FOUND"
        fi
    done

    log ""
    log "Helm releases:"
    for rel_ns in "strimzi-kafka-operator:kafka" "opensearch-operator:opensearch-operator" "azul-infra:azul-infra"; do
        local rel="${rel_ns%%:*}" ns="${rel_ns##*:}"
        if helm status "$rel" -n "$ns" >/dev/null 2>&1; then
            local rev
            rev=$(helm status "$rel" -n "$ns" -o json 2>/dev/null | python3 -c "import sys,json; print(json.load(sys.stdin).get('version','?'))" 2>/dev/null || echo "?")
            log "  $rel ($ns): INSTALLED (revision $rev)"
        else
            log "  $rel ($ns): NOT INSTALLED"
        fi
    done

    log ""
    log "Pods in azul-infra:"
    kubectl get pods -n azul-infra -o wide 2>/dev/null || log "  (namespace not found)"

    log ""
    log "Secrets in azul-infra:"
    kubectl get secrets -n azul-infra --no-headers 2>/dev/null | while read -r line; do log "  $line"; done

    log ""
    log "Certificates:"
    kubectl get certificates -n azul-infra 2>/dev/null || log "  (none)"
}

