# STEP 2: Install Strimzi Kafka Operator
# ═══════════════════════════════════════════════════════════════════════════════
step2_strimzi() {
    log ""
    log "============================================"
    log "=== STEP 2: Install Strimzi Operator ==="
    log "============================================"
    log "Chart: $STRIMZI_CHART"
    log "Namespace: kafka"
    log "Image: quay.io/strimzi/operator:0.50.0"

    if helm status strimzi-kafka-operator -n kafka >/dev/null 2>&1; then
        log "Strimzi already installed, skipping"
    else
        helm install strimzi-kafka-operator "$STRIMZI_CHART" \
            --namespace kafka --create-namespace \
            --set watchAnyNamespace=true \
            --timeout 3m
        log "Strimzi operator installed"
    fi

    log "Waiting for Strimzi operator pod..."
    kubectl wait --for=condition=ready pod -l name=strimzi-cluster-operator \
        -n kafka --timeout=120s
    log "Strimzi operator: READY"
}

