die() { log "FATAL: $*"; exit 1; }

send_discord() {
    local operation="$1" status="$2" details="${3:-}" color
    [ "$status" = "success" ] && color="65280" || color="16711680"
    curl -sf -H "Content-Type: application/json" -d "{
        \"embeds\": [{
            \"title\": \"Azul Infra Install\",
            \"color\": $color,
            \"fields\": [
                {\"name\": \"Operation\", \"value\": \"$operation\", \"inline\": true},
                {\"name\": \"Status\", \"value\": \"$status\", \"inline\": true},
                {\"name\": \"Date\", \"value\": \"$(date '+%Y-%m-%d %H:%M:%S')\", \"inline\": false},
                {\"name\": \"Details\", \"value\": \"${details:-N/A}\", \"inline\": false}
            ]
        }]
    }" "$DISCORD_WEBHOOK" >/dev/null 2>&1 || true
}

# ═══════════════════════════════════════════════════════════════════════════════
# PREFLIGHT — verify all required files exist
# ═══════════════════════════════════════════════════════════════════════════════
preflight() {
    log "=== Preflight Checks ==="
    local ok=true

    for f in "$INFRA_CHART/Chart.yaml" "$INFRA_VALUES" "$STRIMZI_CHART" \
             "$OPENSEARCH_CHART" "$CERTS_SCRIPT" "$KEYCLOAK_SCRIPT"; do
        if [ ! -e "$f" ]; then
            log "MISSING: $f"
            ok=false
        else
            log "  OK: $f"
        fi
    done

    # Check tools
    for cmd in kubectl helm python3 openssl curl; do
        if ! command -v "$cmd" >/dev/null 2>&1; then
            log "MISSING command: $cmd"
            ok=false
        fi
    done

    # Check cluster access
    if ! kubectl cluster-info >/dev/null 2>&1; then
        log "ERROR: Cannot reach Kubernetes cluster (check KUBECONFIG=$KUBECONFIG)"
        ok=false
    fi

    # Check cert-manager
    if ! kubectl get crd certificates.cert-manager.io >/dev/null 2>&1; then
        log "ERROR: cert-manager not installed (required for TLS certificates)"
        ok=false
    fi

    if [ "$ok" = false ]; then
        die "Preflight checks failed — fix the above before continuing"
    fi
    log "All preflight checks passed"
    log ""
}

