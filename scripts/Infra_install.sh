# STEP 1: Generate credentials
# ═══════════════════════════════════════════════════════════════════════════════
step1_credentials() {
    log "============================================"
    log "=== STEP 1: Generate Credentials ==="
    log "============================================"

    # Check if credentials already have static (non-$()) values
    if [ -f "$CREDS_FILE" ]; then
        if grep -q '$(openssl' "$CREDS_FILE" 2>/dev/null; then
            log "WARNING: $CREDS_FILE contains dynamic \$(openssl ...) values"
            log "Regenerating with static values..."
        else
            log "Credentials file exists with static values: $CREDS_FILE"
            return 0
        fi
    fi

    log "Generating new credentials → $CREDS_FILE"
    cat > "$CREDS_FILE" <<EOF
# AZUL Infrastructure Credentials — SENSITIVE — DO NOT COMMIT
# Generated: $(date '+%Y-%m-%d %H:%M:%S')
# These are STATIC values. Do not change after secrets are created in cluster.

## MinIO (Main S3 storage)
S3_ACCESS_KEY=$(openssl rand -hex 16)
S3_SECRET_KEY=$(openssl rand -hex 32)

## OpenSearch Admin
OS_ADMIN_USER=admin
OS_ADMIN_PASS=$(openssl rand -base64 24)

## OpenSearch Dashboard (kibanaserver)
OS_DASH_USER=kibanaserver
OS_DASH_PASS=$(openssl rand -base64 24)

## Keycloak
KC_DB_PASSWORD=$(openssl rand -base64 24)
KC_ADMIN_USER=admin
KC_ADMIN_PASSWORD=$(openssl rand -base64 24)
EOF
    chmod 600 "$CREDS_FILE"
    log "Credentials saved (static values, safe to re-source)"
    log "  File: $CREDS_FILE"
}

# Load credentials from file (key=value, ignoring comments and blanks)
load_creds() {
    if [ ! -f "$CREDS_FILE" ]; then
        die "Credentials file not found: $CREDS_FILE — run step 1 first"
    fi
    if grep -q '$(openssl' "$CREDS_FILE" 2>/dev/null; then
        die "Credentials file has dynamic values — run step 1 to regenerate"
    fi
    while IFS='=' read -r key value; do
        case "$key" in
            S3_ACCESS_KEY)    S3_ACCESS_KEY="$value" ;;
            S3_SECRET_KEY)    S3_SECRET_KEY="$value" ;;
            OS_ADMIN_PASS)    OS_ADMIN_PASS="$value" ;;
            OS_DASH_PASS)     OS_DASH_PASS="$value" ;;
            KC_DB_PASSWORD)   KC_DB_PASSWORD="$value" ;;
            KC_ADMIN_PASSWORD) KC_ADMIN_PASSWORD="$value" ;;
        esac
    done < <(grep -v '^#' "$CREDS_FILE" | grep -v '^\s*$' | grep '=')
    log "Credentials loaded from $CREDS_FILE"
}

