# STEP 9: Bake Test CA into OpenSearch cert bundle
# ═══════════════════════════════════════════════════════════════════════════════
step9_bake_ca() {
    log ""
    log "============================================"
    log "=== STEP 9: Bake CA into OpenSearch ==="
    log "============================================"
    log "This runs 'helm upgrade azul-infra' to push the patched ca-certificates"
    log "file into the opensearch-certs configmap, then restarts OpenSearch."
    log ""

    # Source certificate functions
    source "$CERTS_SCRIPT"

    # Check if already baked
    local has_test_ca
    has_test_ca=$(kubectl exec azul-opensearch-nodes-0 -n azul-infra -- \
        grep -c "Test CA" /usr/share/opensearch/config/certs/ca-certificates 2>/dev/null) || has_test_ca="0"

    if [ "$has_test_ca" -gt 0 ] 2>/dev/null; then
        log "Test CA already in OpenSearch cert bundle — skipping"
        return 0
    fi

    # Ensure chart bundle is patched
    patch_ca_into_chart

    # Helm upgrade to push patched bundle
    log "Running helm upgrade azul-infra..."
    helm upgrade azul-infra "$INFRA_CHART" -n azul-infra -f "$INFRA_VALUES" --timeout 5m
    log "Helm upgrade complete"

    # OpenSearch needs restart to pick up new configmap
    log "Restarting OpenSearch to pick up updated CA bundle..."
    log "(Single-node requires unsafe-bootstrap after restart)"

    # Re-run the bootstrap process
    step7_opensearch_bootstrap

    # Verify CA is now present
    has_test_ca=$(kubectl exec azul-opensearch-nodes-0 -n azul-infra -- \
        grep -c "Test CA" /usr/share/opensearch/config/certs/ca-certificates 2>/dev/null) || has_test_ca="0"
    if [ "$has_test_ca" -gt 0 ] 2>/dev/null; then
        log "Test CA confirmed in OpenSearch cert bundle"
    else
        log "WARNING: Test CA not found in OpenSearch — OIDC may not work"
    fi
}

