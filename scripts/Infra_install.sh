        -l app=keycloak -n azul-infra --timeout=300s 2>/dev/null \
        && log "  Keycloak: READY" || log "  WARNING: Keycloak not ready within 300s"

    log "  OpenSearch will be handled in step 7 (needs unsafe-bootstrap)"
}

# ═══════════════════════════════════════════════════════════════════════════════
# STEP 7: OpenSearch single-node unsafe-bootstrap
# ═══════════════════════════════════════════════════════════════════════════════
step7_opensearch_bootstrap() {
    log ""
    log "============================================"
    log "=== STEP 7: OpenSearch Unsafe-Bootstrap ==="
    log "============================================"
    log "Image for bootstrap job: $OPENSEARCH_IMAGE"
    log ""
    log "OpenSearch single-node requires 'unsafe-bootstrap' after every pod restart."
    log "This runs a Job that modifies the PVC data, then restarts the StatefulSet."

    # Check if OpenSearch is already ready
    local os_ready
    os_ready=$(kubectl get pod azul-opensearch-nodes-0 -n azul-infra \
        -o jsonpath='{.status.conditions[?(@.type=="Ready")].status}' 2>/dev/null || echo "Unknown")

    if [ "$os_ready" = "True" ]; then
        log "OpenSearch already Ready — skipping bootstrap"
        return 0
    fi

    log "OpenSearch not ready (status=$os_ready), running unsafe-bootstrap..."

    # Scale down operator so it doesn't fight us
    log "  Scaling down opensearch-operator..."
    kubectl scale deployment opensearch-operator-controller-manager \
        -n opensearch-operator --replicas=0 2>/dev/null || true
    sleep 5

    # Scale down OpenSearch StatefulSet
    log "  Scaling down azul-opensearch-nodes..."
    kubectl scale statefulset azul-opensearch-nodes -n azul-infra --replicas=0 2>/dev/null || true

    # Wait for pod to terminate
    log "  Waiting for OpenSearch pod to terminate..."
    local attempts=0
    while [ $attempts -lt 30 ]; do
        if ! kubectl get pod azul-opensearch-nodes-0 -n azul-infra >/dev/null 2>&1; then
            break
        fi
        sleep 5
        attempts=$((attempts + 1))
    done

    # Delete old bootstrap job if exists
    kubectl delete job opensearch-unsafe-bootstrap -n azul-infra 2>/dev/null || true

    # Create and run the unsafe-bootstrap Job
    log "  Running unsafe-bootstrap Job..."
    cat <<EOJOB | kubectl apply -f -
apiVersion: batch/v1
kind: Job
metadata:
  name: opensearch-unsafe-bootstrap
  namespace: azul-infra
spec:
  backoffLimit: 1
  template:
    spec:
      restartPolicy: Never
      securityContext:
        runAsUser: 1000
        runAsGroup: 1000
        fsGroup: 1000
      containers:
      - name: bootstrap
        image: ${OPENSEARCH_IMAGE}
        command:
        - /bin/bash
        - -c
        - |
          echo "y" | /usr/share/opensearch/bin/opensearch-node unsafe-bootstrap
        volumeMounts:
        - name: data
          mountPath: /usr/share/opensearch/data
      volumes:
      - name: data
        persistentVolumeClaim:
          claimName: data-azul-opensearch-nodes-0
EOJOB

    log "  Waiting for bootstrap Job to complete..."
    kubectl wait --for=condition=complete job/opensearch-unsafe-bootstrap \
        -n azul-infra --timeout=120s 2>/dev/null \
        && log "  Bootstrap Job: COMPLETED" \
        || log "  WARNING: Bootstrap Job may not have completed"

    # Clean up
    kubectl delete job opensearch-unsafe-bootstrap -n azul-infra 2>/dev/null || true

    # Scale back up
    log "  Scaling up azul-opensearch-nodes..."
    kubectl scale statefulset azul-opensearch-nodes -n azul-infra --replicas=1
    log "  Scaling up opensearch-operator..."
    kubectl scale deployment opensearch-operator-controller-manager \
        -n opensearch-operator --replicas=1 2>/dev/null || true

    # Wait for OpenSearch to come back
    log "  Waiting for OpenSearch pod to be Ready..."
    sleep 30
    kubectl wait --for=condition=ready pod/azul-opensearch-nodes-0 \
        -n azul-infra --timeout=180s 2>/dev/null \
        && log "  OpenSearch: READY" \
        || log "  WARNING: OpenSearch not ready within 180s"
}

