# STEP 8: CoreDNS hosts + Keycloak TLS certificate
# ═══════════════════════════════════════════════════════════════════════════════
step8_coredns_and_keycloak_cert() {
    log ""
    log "============================================"
    log "=== STEP 8: CoreDNS + Keycloak TLS Cert ==="
    log "============================================"

    # Source certificate functions
    source "$CERTS_SCRIPT"

    # --- CoreDNS ---
    log "Checking CoreDNS for azul hosts entries..."
    local COREFILE
    COREFILE=$(kubectl get configmap coredns -n kube-system -o jsonpath='{.data.Corefile}' 2>/dev/null)

    if echo "$COREFILE" | grep -q "${KEYCLOAK_HOST}"; then
        log "CoreDNS already has azul hosts entries"
    else
        log "Adding azul hosts block to CoreDNS..."
        local HOSTS_BLOCK="    hosts {
        ${CLUSTER_IP} ${KEYCLOAK_HOST}
        ${CLUSTER_IP} ${OPENSEARCH_HOST}
        ${CLUSTER_IP} ${AZUL_HOST}
        fallthrough
    }"
        local NEW_COREFILE
        NEW_COREFILE=$(echo "$COREFILE" | HOSTS_BLOCK="$HOSTS_BLOCK" python3 -c "
import sys, os
content = sys.stdin.read()
hosts_block = os.environ['HOSTS_BLOCK']
lines = content.split('\n')
result = []
inserted = False
for line in lines:
    if 'forward' in line and not inserted:
        result.append(hosts_block.rstrip())
        inserted = True
    result.append(line)
if not inserted:
    result2 = []
    for line in reversed(result):
        if line.strip() == '}' and not inserted:
            result2.append(line)
            result2.append(hosts_block.rstrip())
            inserted = True
        else:
            result2.append(line)
    result = list(reversed(result2))
print('\n'.join(result), end='')
")
        kubectl create configmap coredns -n kube-system \
            --from-literal=Corefile="$NEW_COREFILE" \
            --dry-run=client -o yaml | kubectl apply -f -
        kubectl rollout restart deployment coredns -n kube-system
        log "CoreDNS updated with azul hosts"
        sleep 10
    fi

    # --- Keycloak TLS Certificate ---
    log ""
    log "Creating Keycloak TLS certificate (cert-manager)..."
    create_keycloak_cert
    log "Keycloak TLS cert: READY"
}

