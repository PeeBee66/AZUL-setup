# STEP 10: Keycloak setup + verification
# ═══════════════════════════════════════════════════════════════════════════════
step10_keycloak_and_verify() {
    log ""
    log "============================================"
    log "=== STEP 10: Keycloak Setup + Verify ==="
    log "============================================"

    load_creds

    # --- Keycloak realm setup ---
    if [ -f "$KEYCLOAK_SCRIPT" ]; then
        log "Running Keycloak setup: $KEYCLOAK_SCRIPT"
        bash "$KEYCLOAK_SCRIPT"
        log "Keycloak configuration complete"
    else
        die "Keycloak setup script not found: $KEYCLOAK_SCRIPT"
    fi

    # --- Verification ---
    log ""
    log "=== Verification ==="
    local errors=0

    # Check all pods
    log "Checking infra pods..."
    local not_ready
    not_ready=$(kubectl get pods -n azul-infra --no-headers 2>/dev/null \
        | grep -v "Completed" \
        | grep -cvE "([0-9]+)/\1\s+Running" 2>/dev/null) || not_ready="0"
    if [ "$not_ready" != "0" ]; then
        log "WARNING: $not_ready pods not ready in azul-infra"
        kubectl get pods -n azul-infra --no-headers | grep -v "Running\|Completed" || true
        errors=$((errors + 1))
    else
        log "  All infra pods: RUNNING"
    fi

    # Check Keycloak endpoint
    log "Checking Keycloak azul realm..."
    local kc_code
    kc_code=$(curl -k -sf -o /dev/null -w '%{http_code}' \
        -H "Host: ${KEYCLOAK_HOST}" https://${CLUSTER_IP}/realms/azul 2>/dev/null || echo "000")
    if [ "$kc_code" = "200" ]; then
        log "  Keycloak azul realm: OK ($kc_code)"
    else
        log "  WARNING: Keycloak azul realm returned $kc_code"
        errors=$((errors + 1))
    fi

    # Check OpenSearch cluster health
    log "Checking OpenSearch health..."
    local os_health
    os_health=$(kubectl exec azul-opensearch-nodes-0 -n azul-infra -- \
        curl -sf -u "admin:${OS_ADMIN_PASS}" -k https://localhost:9200/_cluster/health 2>/dev/null \
        | python3 -c "import sys,json; print(json.load(sys.stdin).get('status','unknown'))" 2>/dev/null || echo "unknown")
    if [ "$os_health" = "green" ] || [ "$os_health" = "yellow" ]; then
        log "  OpenSearch health: $os_health"
    else
        log "  WARNING: OpenSearch health: $os_health"
        errors=$((errors + 1))
    fi

    # Final status
    log ""
    if [ "$errors" -eq 0 ]; then
        log "=== INFRASTRUCTURE INSTALL COMPLETE — ALL CHECKS PASSED ==="
        send_discord "Infra Install" "success" "All infra pods running, Keycloak configured, OpenSearch healthy"
    else
        log "=== INFRASTRUCTURE INSTALL COMPLETE — $errors WARNING(S) ==="
        log "Check the warnings above. OpenSearch Dashboards may need a restart"
        log "after Keycloak is fully configured:"
        log "  kubectl rollout restart deployment azul-opensearch-dashboards -n azul-infra"
        send_discord "Infra Install" "success" "Install complete with $errors warning(s)"
    fi

    log ""
    log "Pod status:"
    kubectl get pods -n azul-infra -o wide 2>/dev/null || true
}

